    Como secretario tienes acceso operativo casi igual al del rector, con algunas excepciones (ver el último tema).
    Haz clic en cada tema para ver el detalle.
</p>

<div class="d-flex flex-column gap-2 contenedor-manual">

    <details class="border rounded p-3 bg-body" open>
        <summary class="fw-semibold">1. Bienes: registrar y gestionar el ciclo de vida</summary>
        <div class="mt-2 small">
            <ol class="mb-0 ps-3">
                <li><strong>Registrar un bien</strong> (Bienes &gt; Registrar bien): código, descripción, categoría,
                    marca, valor y, si aplica, foto y factura. La categoría es obligatoria — sin ella, el bien no se
                    podrá reintegrar más adelante.</li>
                <li><strong>Asignar</strong> un bien, desde su ficha (o varios a la vez en
                    <strong>Bienes &gt; Acciones masivas &gt; Asignar bienes</strong>). Elige la responsabilidad:
                    <ul class="mt-1">
                        <li><strong>Grupal</strong>: el bien queda en un espacio y responden todos los responsables de ese
                            espacio (por ejemplo, las sillas del Aula 101).</li>
                        <li><strong>Individual</strong>: el bien queda a cargo de una persona y responde solo ella (por ejemplo,
                            el portátil de un docente). Si quieres, indica en qué espacio está guardado.</li>
                    </ul>
                </li>
                <li><strong>Trasladar</strong> un bien asignado a otro espacio o a otra persona, o pasarlo de Grupal a
                    Individual (o al revés). Cada cambio queda en su historial.</li>
                <li><strong>Reintegrar</strong> un bien desde su ficha, o varios a la vez en
                    <strong>Bienes &gt; Acciones masivas &gt; Reintegrar bienes</strong>.</li>
                <li><strong>Dar de baja</strong> un bien, o aprobar/rechazar bajas que otros reporten (ver tema 4).</li>
                <li>Para cargar muchos bienes o fotos de una vez, usa <strong>Bienes &gt; Acciones masivas &gt; Carga
                    masiva de bienes</strong>.</li>
            </ol>
        </div>
    </details>

    <details class="border rounded p-3 bg-body">
        <summary class="fw-semibold">2. Espacios: crear y administrar</summary>
        <div class="mt-2 small">
            <ol class="mb-0 ps-3">
                <li>Entra a <strong>Espacios</strong> para crear aulas, oficinas o bodegas, y asignarles un
                    responsable.</li>
                <li>Puedes activar o desactivar un espacio, y cargar varios de una vez con la carga masiva.</li>
            </ol>
        </div>
    </details>

    <details class="border rounded p-3 bg-body">
        <summary class="fw-semibold">3. Verificación física: jornadas completas</summary>
        <div class="mt-2 small">
            <ol class="mb-0 ps-3">
                <li>Entra a <strong>Verificación física</strong> y pulsa <strong>Nueva jornada</strong> para
                    iniciarla. Mientras esté activa, cualquier usuario puede escanear los bienes de su espacio para
                    confirmarlos o reportar una discrepancia.</li>
                <li>Desde el detalle de la jornada ves lo pendiente, lo confirmado, las discrepancias reportadas y
                    los hallazgos (bienes no registrados) que hayan reportado.</li>
                <li>Cada discrepancia se puede marcar como revisada; cada hallazgo se puede registrar como un bien
                    nuevo o descartar.</li>
                <li>Cuando termine, <strong>cierra la jornada</strong> y exporta el consolidado completo a Excel.</li>
            </ol>
        </div>
    </details>

    <details class="border rounded p-3 bg-body">
        <summary class="fw-semibold">4. Bajas: reportar y aprobar</summary>
        <div class="mt-2 small">
            <ol class="mb-0 ps-3">
                <li>Reporta la baja de un bien desde su ficha o su código QR.</li>
                <li>Entra a <strong>Bajas</strong> para ver todas las reportadas en tu institución y aprobarlas o
                    rechazarlas — mientras no se aprueben, el bien sigue activo en el sistema.</li>
                <li>Al aprobar, el bien queda dado de baja y sale de su espacio. Al rechazar, escribe el motivo: el
                    reporte se conserva con él y quien lo hizo puede verlo.</li>
                <li>En <strong>Solicitudes de reintegro</strong> revisas los pedidos de los docentes: al aprobar uno
                    (con la fecha y el destino) el bien se reintegra; al rechazarlo, escribe una respuesta.</li>
            </ol>
        </div>
    </details>

    <details class="border rounded p-3 bg-body">
        <summary class="fw-semibold">5. Lotes de reintegro y el comprobante oficial (FO-ADMI-009)</summary>
        <div class="mt-2 small">
            <ol class="mb-0 ps-3">
                <li>Después de reintegrar bienes, entra a <strong>Lotes de reintegro</strong> y genera un lote con
                    los movimientos pendientes de agrupar.</li>
                <li>Desde el detalle del lote, descarga el <strong>comprobante</strong>: el formato oficial que
                    exige la Alcaldía, ya organizado por categoría y listo para imprimir.</li>
            </ol>
        </div>
    </details>

    <details class="border rounded p-3 bg-body">
        <summary class="fw-semibold">6. Reportes y cartera</summary>
        <div class="mt-2 small">
            <ol class="mb-0 ps-3">
                <li>Entra a <strong>Reportes</strong> para descargar la cartera de bienes, los reintegros
                    (pendientes o históricos) y el consolidado de jornadas de verificación, en Excel o CSV.</li>
                <li>En <strong>Bienes</strong> puedes filtrar por <strong>Espacio</strong>, <strong>Responsable</strong> y
                    <strong>Responsabilidad</strong> (Grupal, Individual o Sin asignar). <strong>Descargar en Excel</strong> baja
                    la cartera con los filtros que tengas puestos.</li>
                <li>Con un responsable elegido en el filtro aparece <strong>Acta de bienes a cargo</strong>: un Excel con sus
                    bienes individuales y los de sus espacios, para imprimir y firmar (por ejemplo, cuando alguien sale de
                    la institución). También está en <strong>Reportes</strong>.</li>
                <li>En <strong>Cartera (histórico)</strong> registras cada cartera que la institución solicitó por correo
                    y la Alcaldía le envió: el funcionario que la solicitó (se elige de la lista) y su correo, el correo
                    desde el que llegó, la fecha en que se recibió y el archivo. Los registros aparecen debajo del
                    formulario, en la misma ventana, con Descargar, Editar y Eliminar.</li>
            </ol>
        </div>
    </details>

    <details class="border rounded p-3 bg-body">
        <summary class="fw-semibold">7. Formatos de reintegro, de plaqueteo y facturas</summary>
        <div class="mt-2 small">
            <p class="mb-1">
                Estas tres secciones del menú son una biblioteca de evidencia: sirven para archivar en el sistema
                documentos que ya firmaste o recibiste aparte (no los genera MIA).
            </p>
            <ol class="mb-0 ps-3">
                <li><strong>Formatos de reintegro</strong> y <strong>Formatos de plaqueteo</strong>: sube el PDF ya
                    firmado, con su fecha y una descripción.</li>
                <li><strong>Facturas</strong>: sube las facturas administrativas de compras, para tenerlas
                    centralizadas.</li>
                <li>Todo queda en la misma ventana: arriba el formulario y debajo los registros, con
                    <strong>Descargar</strong>, <strong>Editar</strong> (el formulario se llena con sus datos) y
                    <strong>Eliminar</strong> (va a la papelera).</li>
            </ol>
        </div>
    </details>

    <details class="border rounded p-3 bg-body">
        <summary class="fw-semibold">8. Lo que no puedes hacer</summary>
        <div class="mt-2 small">
            <ul class="mb-0 ps-3">
                <li><strong>Usuarios:</strong> puedes verlos en el listado, pero no crearlos, editarlos ni
                    activarlos/desactivarlos — eso le corresponde al rector.</li>
                <li><strong>Instituciones:</strong> solo puedes verla, no editar sus datos.</li>
                <li><strong>Categorías de bienes:</strong> no administras ese catálogo — pídele al rector que cree
                    o ajuste una categoría si te hace falta.</li>
                <li><strong>Instituciones nuevas y "Cargos":</strong> exclusivo del superusuario.</li>
            </ul>
        </div>
    </details>

